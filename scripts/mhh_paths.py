def check():
    """Print every path and whether it exists (python scripts\\mhh_paths.py)."""
    # ENV_OPENVLA_PY / OPENVLA_DIR are not checked: OpenVLA was retired (backup on E:\backup\My-Humanoid-Hand_groupB_2026-11-15)

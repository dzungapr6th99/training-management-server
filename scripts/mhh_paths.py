def dual_import_usd():
    """Newest URDF-importer output for the dual robot (the importer writes YellowArm_Two_ORCA_<n>/ instead of
    overwriting an existing import, so the latest folder is the one made from the current URDF)."""
    c = [d / f"{DUAL_URDF.stem}.usda" for d in DUAL_USD_DIR.glob(f"{DUAL_URDF.stem}*") if d.is_dir()]
    c = [p for p in c if p.exists()]
    return max(c, key=lambda p: p.stat().st_mtime) if c else None
